// ---------------------------------------------------------------------------
// Spy / capturing executor (local to this file)
// ---------------------------------------------------------------------------

// contentCapturingExecutor intercepts deploy.ExecRequest.Content and calls it for every
// agent plan item, recording the generated bytes by agent key. This allows tests to inspect
// what the content-generation callback produces without requiring real file writes.
type contentCapturingExecutor struct {
	capturedContents map[string][]byte // agentKey → bytes from Content callback
	result           deploy.ExecResult
}

func (e *contentCapturingExecutor) Execute(ctx context.Context, req deploy.ExecRequest) (deploy.ExecResult, error) {
	e.capturedContents = make(map[string][]byte)
	for _, item := range req.Plan.Items {
		if item.Ref.Kind == domain.ArtifactAgent {
			content, err := req.Content(item)
			if err == nil {
				e.capturedContents[item.Ref.Key] = content
			}
		}
	}
	return e.result, nil
}

