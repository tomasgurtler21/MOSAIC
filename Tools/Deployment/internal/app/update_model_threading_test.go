// update_model_threading_test.go verifies Stage 3: threading of deployed model selections
// through the Update flow.
//
// The Update flow must:
//   - Build a model selection map from the probed deployed state
//   - Feed this map into plan.Input.Models (so the planner receives it)
//   - Feed the same map into buildContent (so the transform preserves the model key)
//   - Produce regenerated content that preserves the model ID found in the deployed file
//   - Not ask any model-selection questions (QTierModel, QAgentModel)
//   - Not persist any tier model mappings to UserConfig
//
// Tests marked "will FAIL against the current implementation" are in TDD RED phase.
// They will pass once I3.2 and I3.3 are implemented.

