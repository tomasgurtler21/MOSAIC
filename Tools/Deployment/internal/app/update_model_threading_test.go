// TestUpdate_AgentWithDeployedModel_GeneratedContentPreservesModel verifies that the content
// generated by the Update flow for an agent whose deployed file carries a model ID also
// contains that model ID. This is the key end-to-end invariant: the deployed model selection
// must reach buildContent so the transform writes the model key rather than stripping it.
//
// This test will FAIL against the current implementation because buildContent is called with
// nil for the models argument, causing the transform to treat the model as unresolved and
// omit the model key from the generated content.
func TestUpdate_AgentWithDeployedModel_GeneratedContentPreservesModel(t *testing.T) {
	ws := t.TempDir()

	// Write a deployed agent file that embeds a model ID.
	deployedContent := []byte("---\nversion: \"1.0\"\nmodel: \"claude-opus-4-5\"\n---\nAgent body.\n")
	writeTempFile(t, ws, "test-runner.md", deployedContent)

	// Configure a harness with ModelKey so the transform knows which frontmatter key to write.
	mod := newModelKeyModule()

	// The stub planner returns an ActionUpdate item for test-runner so the Content callback
	// is exercised for an agent whose deployed file carries a model.
	updateItem := domain.PlanItem{
		Ref:        domain.ArtifactRef{Kind: domain.ArtifactAgent, Key: "test-runner"},
		TargetPath: "test-runner.md",
		Action:     domain.ActionUpdate,
	}

	capExec := &contentCapturingExecutor{
		result: deploy.ExecResult{DeploymentRoot: ws},
	}

	stub := interactiontest.NewBuilder().AnswerReview(true).Build()
	deps, _ := newBaseDeps(t, stub)
	deps.Registry = newMinimalRegistry(mod)
	deps.Planner = &stubPlanner{plan: domain.Plan{
		Mode:          domain.ModeUpdateWorkspace,
		Harness:       minimalHarness,
		WorkspacePath: ws,
		Items:         []domain.PlanItem{updateItem},
	}}
	deps.Executor = capExec
	svc := app.New(deps)

	_, err := svc.Update(context.Background(), app.UpdateRequest{
		HarnessID:       "stub-harness",
		WorkspacePath:   ws,
		AddWorkflowIDs:  []string{"quick-fix"},
		AutoConfirmPlan: true,
	})
	if err != nil {
		t.Fatalf("Update: %v", err)
	}

	// Assert — the generated content for test-runner must include the deployed model ID.
	content, ok := capExec.capturedContents["test-runner"]
	if !ok {
		t.Fatal("Content callback was not called for test-runner; " +
			"the capturing executor must have invoked Content(item) for the ActionUpdate plan item")
	}
	if !strings.Contains(string(content), "claude-opus-4-5") {
		t.Errorf("generated content for test-runner does not contain the deployed model ID %q; "+
			"the Update flow must thread the deployed model selection into buildContent so the "+
			"transform writes model: %q rather than stripping the model key.\n"+
			"generated content:\n%s",
			"claude-opus-4-5", "claude-opus-4-5", content)
	}
}

// TestUpdate_AgentWithDeployedModel_PlanInputAndContentReceiveSameModelID verifies that
// plan.Input.Models and the content generated by the Content callback both carry the same
// model ID. This confirms that the same map instance feeds both paths rather than two
// independently derived values, upholding the critical consistency invariant from the design.
//
// This test will FAIL against the current implementation.
func TestUpdate_AgentWithDeployedModel_PlanInputAndContentReceiveSameModelID(t *testing.T) {
	ws := t.TempDir()

	const deployedModelID = "claude-sonnet-4"
	deployedContent := []byte("---\nversion: \"1.0\"\nmodel: \"" + deployedModelID + "\"\n---\nAgent body.\n")
	writeTempFile(t, ws, "test-runner.md", deployedContent)

	mod := newModelKeyModule()

	updateItem := domain.PlanItem{
		Ref:        domain.ArtifactRef{Kind: domain.ArtifactAgent, Key: "test-runner"},
		TargetPath: "test-runner.md",
		Action:     domain.ActionUpdate,
	}

	capExec := &contentCapturingExecutor{
		result: deploy.ExecResult{DeploymentRoot: ws},
	}

	// Use a plannerAndCapture that both records the plan.Input and returns a plan with items.
	type plannerAndCapture struct {
		spyPlanner
	}

	spy := &spyPlanner{response: domain.Plan{
		Mode:          domain.ModeUpdateWorkspace,
		Harness:       minimalHarness,
		WorkspacePath: ws,
		Items:         []domain.PlanItem{updateItem},
	}}

	stub := interactiontest.NewBuilder().AnswerReview(true).Build()
	deps, _ := newBaseDeps(t, stub)
	deps.Registry = newMinimalRegistry(mod)
	deps.Planner = spy
	deps.Executor = capExec
	svc := app.New(deps)

	_, err := svc.Update(context.Background(), app.UpdateRequest{
		HarnessID:       "stub-harness",
		WorkspacePath:   ws,
		AddWorkflowIDs:  []string{"quick-fix"},
		AutoConfirmPlan: true,
	})
	if err != nil {
		t.Fatalf("Update: %v", err)
	}

	// Check plan.Input.Models has the correct model ID.
	captured := spy.lastCaptured(t)
	var planModelID string
	if captured.Models != nil {
		if sel, ok := captured.Models["test-runner"]; ok {
			planModelID = sel.ModelID
		}
	}
	if planModelID != deployedModelID {
		t.Errorf("plan.Input.Models[\"test-runner\"].ModelID = %q, want %q; "+
			"the planner must receive the deployed model ID", planModelID, deployedModelID)
	}

	// Check generated content also has the correct model ID.
	content, ok := capExec.capturedContents["test-runner"]
	if !ok {
		t.Fatal("Content callback was not called for test-runner; prerequisite for consistency check")
	}
	if !strings.Contains(string(content), deployedModelID) {
		t.Errorf("generated content does not contain the deployed model ID %q; "+
			"both plan.Input.Models and the content-generation step must carry the same model ID.\n"+
			"generated content:\n%s", deployedModelID, content)
	}
}

