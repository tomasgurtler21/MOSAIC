// TestUpdate_PlanInputModelsAndContentShareConsistentModelID verifies that the model ID
// ultimately seen by the planner and the model ID written into the generated content are
// consistent with each other. If they were derived independently, a bug could cause the
// planner to suppress a gap while the transform still strips the model key.
//
// Setup: single agent with an embedded model; use both a spyPlanner (to capture Models)
// and a contentCapturingExecutor (to inspect generated bytes). Both must show the same ID.
//
// This test will FAIL against the current implementation.
func TestUpdate_PlanInputModelsAndContentShareConsistentModelID(t *testing.T) {
	ws := t.TempDir()
	const deployedModelID = "claude-haiku-4"

	deployedContent := []byte("---\nversion: \"1.0\"\nmodel: \"" + deployedModelID + "\"\n---\nAgent.\n")
	writeTempFile(t, ws, "test-runner.md", deployedContent)

	mod := newModelKeyModule()

	updateItem := domain.PlanItem{
		Ref:        domain.ArtifactRef{Kind: domain.ArtifactAgent, Key: "test-runner"},
		TargetPath: "test-runner.md",
		Action:     domain.ActionUpdate,
	}

	capExec := &contentCapturingExecutor{result: deploy.ExecResult{DeploymentRoot: ws}}
	spy := &spyPlanner{response: domain.Plan{
		Mode:    domain.ModeUpdateWorkspace,
		Harness: minimalHarness,
		WorkspacePath: ws,
		Items:   []domain.PlanItem{updateItem},
	}}

	stub := interactiontest.NewBuilder().AnswerReview(true).Build()
	deps, _ := newBaseDeps(t, stub)
	deps.Registry = newMinimalRegistry(mod)
	deps.Planner = spy
	deps.Executor = capExec
	svc := app.New(deps)

	_, err := svc.Update(context.Background(), app.UpdateRequest{
		HarnessID:       "stub-harness",
		WorkspacePath:   ws,
		AddWorkflowIDs:  []string{"quick-fix"},
		AutoConfirmPlan: true,
	})
	if err != nil {
		t.Fatalf("Update: %v", err)
	}

	captured := spy.lastCaptured(t)

	// plan.Input.Models must carry the deployed model ID.
	planHasModel := false
	if captured.Models != nil {
		if sel, ok := captured.Models["test-runner"]; ok && sel.ModelID == deployedModelID {
			planHasModel = true
		}
	}
	if !planHasModel {
		t.Errorf("plan.Input.Models[\"test-runner\"].ModelID != %q; "+
			"planner must receive the deployed model ID", deployedModelID)
	}

	// Generated content must also carry the deployed model ID.
	content, ok := capExec.capturedContents["test-runner"]
	if !ok {
		t.Fatal("Content callback was not called for test-runner; prerequisite for consistency check")
	}
	contentHasModel := strings.Contains(string(content), deployedModelID)
	if !contentHasModel {
		t.Errorf("generated content does not contain the deployed model ID %q; "+
			"the content-generation step and the planner must use the same model selection "+
			"(critical consistency invariant: same map instance feeds both paths).\n"+
			"generated content:\n%s", deployedModelID, content)
	}
}

