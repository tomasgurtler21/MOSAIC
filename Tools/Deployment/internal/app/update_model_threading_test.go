// newModelKeyModule returns a stubHarnessModule whose descriptor declares "model" as the
// frontmatter key for model selection. Tests that verify content-generation behaviour
// require the harness to emit a model key; the default stub module does not.
func newModelKeyModule() *stubHarnessModule {
	return &stubHarnessModule{
		ref: minimalHarness,
		descriptor: domain.HarnessDescriptor{
			ID:          "stub-harness",
			DisplayName: "Stub Harness",
			Models:      domain.ModelCatalog{IDs: []string{"model-a", "model-b"}},
			Frontmatter: domain.FrontmatterSpec{ModelKey: "model"},
		},
	}
}

